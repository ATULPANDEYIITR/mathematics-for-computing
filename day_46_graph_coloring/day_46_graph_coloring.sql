-- PostgreSQL 15+
-- Graph coloring database model for university exam timetable construction.
-- Vertices are exams; edges represent shared-student conflicts.
-- Colors represent time slots. A valid coloring assigns different slots
-- to adjacent vertices.

BEGIN;

DROP VIEW IF EXISTS exam_slot_conflicts;
DROP VIEW IF EXISTS exam_coloring_report;
DROP TABLE IF EXISTS exam_assignments;
DROP TABLE IF EXISTS exam_conflicts;
DROP TABLE IF EXISTS enrollments;
DROP TABLE IF EXISTS exams;
DROP TABLE IF EXISTS time_slots;
DROP TABLE IF EXISTS students;

CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
    email TEXT NOT NULL UNIQUE
);

CREATE TABLE time_slots (
    slot_id INTEGER PRIMARY KEY,
    slot_label TEXT NOT NULL UNIQUE,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    CHECK (ends_at > starts_at)
);

CREATE TABLE exams (
    exam_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code TEXT NOT NULL UNIQUE,
    course_title TEXT NOT NULL CHECK (length(trim(course_title)) > 0),
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'ready', 'scheduled', 'cancelled'))
);

CREATE TABLE enrollments (
    student_id BIGINT NOT NULL REFERENCES students(student_id),
    exam_id BIGINT NOT NULL REFERENCES exams(exam_id),
    PRIMARY KEY (student_id, exam_id)
);

-- An undirected conflict is stored once with the lower exam ID first.
-- The constraint prevents self-conflicts and duplicate reverse edges.
CREATE TABLE exam_conflicts (
    exam_id_low BIGINT NOT NULL REFERENCES exams(exam_id),
    exam_id_high BIGINT NOT NULL REFERENCES exams(exam_id),
    shared_student_count INTEGER NOT NULL CHECK (shared_student_count > 0),
    PRIMARY KEY (exam_id_low, exam_id_high),
    CHECK (exam_id_low < exam_id_high)
);

CREATE TABLE exam_assignments (
    exam_id BIGINT PRIMARY KEY REFERENCES exams(exam_id),
    slot_id INTEGER NOT NULL REFERENCES time_slots(slot_id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by TEXT NOT NULL CHECK (length(trim(assigned_by)) > 0)
);

CREATE INDEX enrollments_exam_student_idx
    ON enrollments(exam_id, student_id);

CREATE INDEX exam_assignments_slot_idx
    ON exam_assignments(slot_id, exam_id);

CREATE INDEX exam_conflicts_high_idx
    ON exam_conflicts(exam_id_high, exam_id_low);

