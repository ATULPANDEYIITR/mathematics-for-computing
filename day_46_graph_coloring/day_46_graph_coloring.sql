CREATE VIEW exam_coloring_report AS
SELECT
    e.exam_id,
    e.course_code,
    e.course_title,
    e.status,
    a.slot_id,
    ts.slot_label,
    ts.starts_at,
    ts.ends_at,
    CASE WHEN a.exam_id IS NULL THEN 'unassigned' ELSE 'assigned' END
        AS assignment_state
FROM exams AS e
LEFT JOIN exam_assignments AS a ON a.exam_id = e.exam_id
LEFT JOIN time_slots AS ts ON ts.slot_id = a.slot_id;

-- Each returned row is a violated graph-coloring edge.
CREATE VIEW exam_slot_conflicts AS
SELECT
    c.exam_id_low,
    low_exam.course_code AS low_course,
    c.exam_id_high,
    high_exam.course_code AS high_course,
    a_low.slot_id,
    c.shared_student_count
FROM exam_conflicts AS c
JOIN exam_assignments AS a_low
  ON a_low.exam_id = c.exam_id_low
JOIN exam_assignments AS a_high
  ON a_high.exam_id = c.exam_id_high
JOIN exams AS low_exam ON low_exam.exam_id = c.exam_id_low
JOIN exams AS high_exam ON high_exam.exam_id = c.exam_id_high
WHERE a_low.slot_id = a_high.slot_id;

COMMIT;

-- Inspect the generated conflict graph.
SELECT
    low_exam.course_code AS exam_a,
    high_exam.course_code AS exam_b,
    c.shared_student_count
FROM exam_conflicts AS c
JOIN exams AS low_exam ON low_exam.exam_id = c.exam_id_low
JOIN exams AS high_exam ON high_exam.exam_id = c.exam_id_high
ORDER BY exam_a, exam_b;

-- Inspect the timetable and verify that every assigned edge has different colors.
SELECT * FROM exam_coloring_report ORDER BY slot_id, course_code;
SELECT * FROM exam_slot_conflicts;

-- Every ready exam must have an assignment before publication.
SELECT e.exam_id, e.course_code
FROM exams AS e
LEFT JOIN exam_assignments AS a ON a.exam_id = e.exam_id
WHERE e.status = 'ready'
  AND a.exam_id IS NULL;

-- Aggregate color-class sizes. A color class must be an independent set.
SELECT
    ts.slot_id,
    ts.slot_label,
    COUNT(a.exam_id) AS exams_in_slot
FROM time_slots AS ts
LEFT JOIN exam_assignments AS a ON a.slot_id = ts.slot_id
GROUP BY ts.slot_id, ts.slot_label
ORDER BY ts.slot_id;

-- Report the number of colors used and the conflict count.
SELECT
    COUNT(DISTINCT a.slot_id) AS colors_used,
    (SELECT COUNT(*) FROM exam_conflicts) AS graph_edges,
    (SELECT COUNT(*) FROM exam_slot_conflicts) AS violated_edges
FROM exam_assignments AS a;

-- Bipartiteness test for this graph can be implemented using recursive
-- breadth-first search with a color map. Recursive SQL alone is not a
-- convenient general-purpose mutable-coloring engine, so the following
-- query reports local triangle witnesses, which prove non-bipartiteness.
SELECT
    a.exam_id_low AS vertex_a,
    a.exam_id_high AS vertex_b,
    b.exam_id_high AS vertex_c
FROM exam_conflicts AS a
JOIN exam_conflicts AS b
  ON b.exam_id_low = a.exam_id_high
JOIN exam_conflicts AS c
  ON c.exam_id_low = a.exam_id_low
 AND c.exam_id_high = b.exam_id_high
WHERE a.exam_id_low < a.exam_id_high
  AND a.exam_id_high < b.exam_id_high
LIMIT 20;

-- Demonstrate transactional rollback for a conflicting assignment.
-- The temporary invalid change is detected by querying exam_slot_conflicts,
-- then rolled back so that the committed timetable remains unchanged.
BEGIN;

UPDATE exam_assignments
SET slot_id = 0
WHERE exam_id = 102;

SELECT * FROM exam_slot_conflicts;

ROLLBACK;

-- Final integrity checks. These queries should return zero rows or zero counts.
SELECT * FROM exam_slot_conflicts;

SELECT e.exam_id, e.course_code
FROM exams AS e
LEFT JOIN exam_assignments AS a ON a.exam_id = e.exam_id
WHERE e.status = 'scheduled'
  AND a.exam_id IS NULL;

