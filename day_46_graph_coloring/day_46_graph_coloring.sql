-- Generate conflict edges from the enrollment relation.
-- The self-join counts distinct shared students for every exam pair.
INSERT INTO exam_conflicts (
    exam_id_low, exam_id_high, shared_student_count
)
SELECT
    LEAST(left_enrollment.exam_id, right_enrollment.exam_id),
    GREATEST(left_enrollment.exam_id, right_enrollment.exam_id),
    COUNT(DISTINCT left_enrollment.student_id)::INTEGER
FROM enrollments AS left_enrollment
JOIN enrollments AS right_enrollment
  ON left_enrollment.student_id = right_enrollment.student_id
 AND left_enrollment.exam_id < right_enrollment.exam_id
GROUP BY
    LEAST(left_enrollment.exam_id, right_enrollment.exam_id),
    GREATEST(left_enrollment.exam_id, right_enrollment.exam_id);

