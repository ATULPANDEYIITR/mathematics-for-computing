-- Divisibility query: identify repository IDs divisible by 2 and 3.
SELECT
    repository_id,
    organization_name,
    repository_name,
    numeric_identifier
FROM repository_identifiers
WHERE numeric_identifier % 2 = 0
  AND numeric_identifier % 3 = 0
ORDER BY numeric_identifier;

-- Prime/composite classification report.
SELECT
    repository_id,
    organization_name,
    repository_name,
    numeric_identifier,
    classification,
    total_prime_factors
FROM repository_number_profiles
ORDER BY numeric_identifier;

-- Factorization report.
SELECT
    f.factorization_id,
    r.organization_name,
    r.repository_name,
    f.input_value,
    f.classification,
    pf.prime_value,
    pf.exponent
FROM factorization_runs AS f
JOIN repository_identifiers AS r
    ON r.repository_id = f.repository_id
LEFT JOIN prime_factors AS pf
    ON pf.factorization_id = f.factorization_id
ORDER BY f.input_value, pf.prime_value;

-- CTE: find identifiers sharing a non-trivial common divisor.
WITH pairs AS (
    SELECT
        a.repository_id AS left_repository_id,
        b.repository_id AS right_repository_id,
        a.numeric_identifier AS left_value,
        b.numeric_identifier AS right_value
    FROM repository_identifiers AS a
    JOIN repository_identifiers AS b
        ON a.repository_id < b.repository_id
)
SELECT
    left_repository_id,
    right_repository_id,
    left_value,
    right_value,
    number_theory_gcd(left_value, right_value) AS common_divisor
FROM pairs
WHERE number_theory_gcd(left_value, right_value) > 1
ORDER BY common_divisor DESC;

-- Aggregate report: how many identifiers belong to each mathematical class.
SELECT
    classification,
    COUNT(*) AS repository_count
FROM repository_number_profiles
GROUP BY classification
ORDER BY classification;

-- Transactional demonstration:
-- the entire batch insert succeeds or rolls back as one unit.
