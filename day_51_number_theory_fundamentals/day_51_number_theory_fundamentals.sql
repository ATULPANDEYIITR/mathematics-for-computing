-- Topic: Number Theory Fundamentals
-- PostgreSQL model:
-- divisibility, primes, composites, factors, GCD, and workload partitioning.
--
-- The script is self-contained and can be executed in a fresh PostgreSQL
-- database. PostgreSQL BIGINT is used for exact signed 64-bit integers.

DROP SCHEMA IF EXISTS number_theory_lab CASCADE;
CREATE SCHEMA number_theory_lab;

SET search_path = number_theory_lab, public;

CREATE TABLE repository_identifiers (
    repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_name TEXT NOT NULL,
    repository_name TEXT NOT NULL,
    numeric_identifier BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT repository_name_unique
        UNIQUE (organization_name, repository_name),

    CONSTRAINT numeric_identifier_positive
        CHECK (numeric_identifier > 0)
);

CREATE TABLE factorization_runs (
    factorization_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id BIGINT NOT NULL
        REFERENCES repository_identifiers(repository_id)
        ON DELETE CASCADE,
    input_value BIGINT NOT NULL,
    classification TEXT NOT NULL,
    factor_count INTEGER NOT NULL,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT factorization_input_positive
        CHECK (input_value > 0),

    CONSTRAINT factorization_classification_valid
        CHECK (classification IN ('unit', 'prime', 'composite')),

    CONSTRAINT factor_count_nonnegative
        CHECK (factor_count >= 0)
);

CREATE TABLE prime_factors (
    factorization_id BIGINT NOT NULL
        REFERENCES factorization_runs(factorization_id)
        ON DELETE CASCADE,
    prime_value BIGINT NOT NULL,
    exponent INTEGER NOT NULL,

    PRIMARY KEY (factorization_id, prime_value),

    CONSTRAINT prime_value_positive
        CHECK (prime_value > 1),

    CONSTRAINT exponent_positive
        CHECK (exponent > 0)
);

CREATE TABLE workload_batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_name TEXT NOT NULL UNIQUE,
    first_quantity BIGINT NOT NULL,
    second_quantity BIGINT NOT NULL,
    greatest_common_divisor BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT quantities_positive
        CHECK (first_quantity > 0 AND second_quantity > 0)
);

CREATE INDEX idx_repository_identifiers_numeric
    ON repository_identifiers (numeric_identifier);

CREATE INDEX idx_prime_factors_prime
    ON prime_factors (prime_value);

CREATE OR REPLACE FUNCTION number_theory_gcd(
    a BIGINT,
    b BIGINT
)
RETURNS BIGINT
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    x BIGINT := ABS(a);
    y BIGINT := ABS(b);
    remainder BIGINT;
BEGIN
    IF x = 0 AND y = 0 THEN
        RAISE EXCEPTION 'gcd(0, 0) is undefined';
    END IF;

    -- Euclid's algorithm repeatedly replaces (x,y) with (y,x mod y).
    WHILE y <> 0 LOOP
        remainder := x % y;
        x := y;
        y := remainder;
    END LOOP;

    RETURN x;
END;
$$;

CREATE OR REPLACE FUNCTION number_theory_is_prime(
    n BIGINT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    candidate BIGINT;
BEGIN
    IF n < 2 THEN
        RETURN FALSE;
    END IF;

    IF n = 2 THEN
        RETURN TRUE;
    END IF;

    IF n % 2 = 0 THEN
        RETURN FALSE;
    END IF;

    candidate := 3;

    WHILE candidate <= n / candidate LOOP
        IF n % candidate = 0 THEN
            RETURN FALSE;
        END IF;

        candidate := candidate + 2;
    END LOOP;

    RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION number_theory_classify(
    n BIGINT
)
RETURNS TEXT
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
BEGIN
    IF n < 0 THEN
        RETURN 'negative';
    ELSIF n = 0 THEN
        RETURN 'zero';
    ELSIF n = 1 THEN
        RETURN 'unit';
    ELSIF number_theory_is_prime(n) THEN
        RETURN 'prime';
    ELSE
        RETURN 'composite';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION number_theory_factor_count(
    n BIGINT
)
RETURNS INTEGER
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    candidate BIGINT;
    remaining BIGINT := n;
    total INTEGER := 0;
BEGIN
    IF n <= 0 THEN
        RAISE EXCEPTION 'Factor count requires a positive integer';
    END IF;

    WHILE remaining % 2 = 0 AND remaining > 1 LOOP
        total := total + 1;
        remaining := remaining / 2;
    END LOOP;

    candidate := 3;

    WHILE candidate <= remaining / candidate LOOP
        WHILE remaining % candidate = 0 LOOP
            total := total + 1;
            remaining := remaining / candidate;
        END LOOP;

        candidate := candidate + 2;
    END LOOP;

    IF remaining > 1 THEN
        total := total + 1;
    END IF;

    RETURN total;
END;
$$;

CREATE OR REPLACE FUNCTION calculate_batch_gcd()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.greatest_common_divisor :=
        number_theory_gcd(
            NEW.first_quantity,
            NEW.second_quantity
        );

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_calculate_batch_gcd
BEFORE INSERT OR UPDATE OF first_quantity, second_quantity
ON workload_batches
FOR EACH ROW
EXECUTE FUNCTION calculate_batch_gcd();

