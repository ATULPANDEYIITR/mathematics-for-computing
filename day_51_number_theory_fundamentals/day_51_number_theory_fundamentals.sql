    ('transactional-example', 252, 105);

SAVEPOINT after_valid_insert;

-- This statement would violate the positive-quantity CHECK constraint.
-- It is deliberately handled inside a nested transaction block.
DO $$
BEGIN
    BEGIN
        INSERT INTO workload_batches
            (batch_name, first_quantity, second_quantity)
        VALUES
            ('invalid-example', 0, 105);
    EXCEPTION
        WHEN check_violation THEN
            RAISE NOTICE 'Invalid workload rejected by database constraint';
    END;
END;
$$;

COMMIT;

